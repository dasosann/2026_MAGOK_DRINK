def categorize(name, members):
    text = (name + ' ' + ' '.join(members)).lower().replace(' ', '')
    
    # 1. Direct matches ignoring spaces
    for cat, kws in categories.items():
        if any(kw.lower().replace(' ', '') in text for kw in kws):
            return cat
            
    # 2. Defaults if unmapped
    if '주식회사' in text or '상사' in text:
        return '기타'
        
    return '기타'

result = {}
unmatched = []
for b in booths:
    cat = categorize(b['name'], b['members'])
    result[b['id']] = cat
    if cat == '기타':
        unmatched.append(b)

with open('src/data/booth-categories.json', 'w', encoding='utf-8') as f:
    json.dump(result, f, ensure_ascii=False, indent=2)

print(f"Matched {len(result) - len(unmatched)}, Unmatched: {len(unmatched)}")
